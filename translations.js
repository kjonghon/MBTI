window.MINDMETRIC_LANGUAGE_NAMES = Object.fromEntries(
  Object.entries(window.MINDMETRIC_I18N).map(([code, locale]) => [code, locale.name])
);

const originalTextNodes = new WeakMap();
const supportedSiteLanguages = Object.keys(window.MINDMETRIC_I18N);
const languageFlags = {
  ru: "ru",
  kk: "kz",
  en: "gb",
  es: "es",
  zh: "cn",
  ar: "sa",
  ko: "kr"
};

function normalizeTranslationKey(value) {
  return value.replace(/\s+/g, " ").trim();
}

function setLanguageMenuOpen(isOpen) {
  const button = document.getElementById("language-select");
  const menu = document.getElementById("language-menu");
  if (!button || !menu) return;
  menu.hidden = !isOpen;
  button.setAttribute("aria-expanded", String(isOpen));
}

function toggleLanguageMenu() {
  const menu = document.getElementById("language-menu");
  if (menu) setLanguageMenuOpen(menu.hidden);
}

function closeLanguageMenu(returnFocus = false) {
  setLanguageMenuOpen(false);
  if (returnFocus) document.getElementById("language-select")?.focus();
}

function renderLanguageMenu(selectedLanguage) {
  const menu = document.getElementById("language-menu");
  if (!menu) return;

  menu.replaceChildren();
  for (const [code, locale] of Object.entries(window.MINDMETRIC_I18N)) {
    const option = document.createElement("button");
    option.type = "button";
    option.className = "language-option inline-flex w-full items-center gap-2 whitespace-nowrap px-3 py-2 text-start text-sm text-slate-700 hover:bg-indigo-50";
    option.setAttribute("role", "menuitemradio");
    option.setAttribute("aria-checked", String(code === selectedLanguage));
    option.onclick = () => {
      closeLanguageMenu();
      changeLanguage(code);
    };

    const flag = document.createElement("img");
    flag.src = `./assets/flags/${languageFlags[code]}.svg`;
    flag.alt = "";
    flag.setAttribute("aria-hidden", "true");
    flag.className = "h-4 w-5 rounded-sm object-cover";

    const name = document.createElement("span");
    name.textContent = locale.name;
    option.append(flag, name);
    menu.append(option);
  }
}

function applySiteLanguage(language) {
  const locale = window.MINDMETRIC_I18N[language] || window.MINDMETRIC_I18N.ru;
  const selectedLanguage = window.MINDMETRIC_I18N[language] ? language : "ru";
  const root = document.documentElement;
  root.lang = selectedLanguage;
  root.dir = locale.dir;
  const isPrivacyPage = location.pathname.endsWith("/privacy.html");
  document.title = isPrivacyPage ? locale.privacyTitle : locale.pageTitle;

  const description = document.querySelector('meta[name="description"]');
  if (description) description.content = isPrivacyPage ? locale.privacyDescription : locale.description;

  const languageSelect = document.getElementById("language-select");
  if (languageSelect) {
    languageSelect.setAttribute("aria-label", locale.languageLabel);
    document.getElementById("language-name").textContent = locale.name;
    document.getElementById("language-flag").src = `./assets/flags/${languageFlags[selectedLanguage]}.svg`;
    renderLanguageMenu(selectedLanguage);
  }
  document.querySelectorAll("[aria-label]").forEach(element => {
    const originalLabel = element.dataset.originalAriaLabel || element.getAttribute("aria-label");
    if (!element.dataset.originalAriaLabel) element.dataset.originalAriaLabel = originalLabel;
    const translatedLabel = locale.text[normalizeTranslationKey(originalLabel)];
    if (translatedLabel !== undefined) element.setAttribute("aria-label", translatedLabel);
  });

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    const parentTag = node.parentElement?.tagName;
    if (!parentTag || ["SCRIPT", "STYLE", "SELECT", "OPTION"].includes(parentTag)) continue;
    if (!originalTextNodes.has(node)) originalTextNodes.set(node, node.textContent);

    const original = originalTextNodes.get(node);
    const key = normalizeTranslationKey(original);
    const translated = locale.text[key];
    if (translated === undefined) {
      node.textContent = original;
      continue;
    }

    const leadingWhitespace = original.match(/^\s*/)?.[0] || "";
    const trailingWhitespace = original.match(/\s*$/)?.[0] || "";
    node.textContent = `${leadingWhitespace}${translated}${trailingWhitespace}`;
  }

  if (document.body) document.body.dir = locale.dir;
  if (typeof window.refreshLocalizedView === "function") window.refreshLocalizedView();
}

function changeLanguage(language) {
  if (!window.MINDMETRIC_I18N[language]) return;

  try {
    localStorage.setItem("mindmetric-language", language);
  } catch (error) {
    console.error("언어 설정을 저장하지 못했습니다.", error);
  }

  applySiteLanguage(language);
}

document.addEventListener("click", event => {
  if (!document.getElementById("language-picker")?.contains(event.target)) {
    closeLanguageMenu();
  }
});
document.addEventListener("keydown", event => {
  const menu = document.getElementById("language-menu");
  if (!menu || menu.hidden) return;

  if (event.key === "Escape") {
    event.preventDefault();
    closeLanguageMenu(true);
    return;
  }

  const options = [...menu.querySelectorAll('[role="menuitemradio"]')];
  const currentIndex = options.indexOf(document.activeElement);
  let nextIndex;
  if (event.key === "ArrowDown") nextIndex = (currentIndex + 1) % options.length;
  else if (event.key === "ArrowUp") nextIndex = (currentIndex - 1 + options.length) % options.length;
  else if (event.key === "Home") nextIndex = 0;
  else if (event.key === "End") nextIndex = options.length - 1;
  if (nextIndex !== undefined) {
    event.preventDefault();
    options[nextIndex].focus();
  }
});

window.applySiteLanguage = applySiteLanguage;
window.changeLanguage = changeLanguage;
window.toggleLanguageMenu = toggleLanguageMenu;
window.getSiteLocale = function () {
  return window.MINDMETRIC_I18N[document.documentElement.lang] || window.MINDMETRIC_I18N.ru;
};
